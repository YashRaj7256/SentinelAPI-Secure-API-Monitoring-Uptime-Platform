package com.sentinelapi.mapper;

import org.springframework.stereotype.Component;

import com.sentinelapi.dto.CreateMonitorRequest;
import com.sentinelapi.dto.MonitorResponse;
import com.sentinelapi.entity.HttpMethod;
import com.sentinelapi.entity.Monitor;

/**
 * Maps between {@link Monitor} entities and DTOs.
 *
 * <h3>Why a Dedicated Mapper?</h3>
 * <ul>
 *   <li><strong>Single Responsibility</strong> — conversion logic lives here,
 *       not scattered across services</li>
 *   <li><strong>Testability</strong> — mapping can be unit-tested independently</li>
 *   <li><strong>Reusability</strong> — multiple services or controllers can use
 *       the same mapper</li>
 *   <li><strong>Change isolation</strong> — if the entity adds a field, only the
 *       mapper needs to change (not every service that creates a response)</li>
 * </ul>
 *
 * <h3>Why Not Use MapStruct?</h3>
 * <p>MapStruct is a compile-time code generator that auto-generates mapper
 * implementations from interfaces. It's excellent for large projects with
 * many entities. For SentinelAPI (a learning project with 2 entities),
 * hand-written mappers are clearer and more educational. You see exactly
 * what each field maps to.
 *
 * <h3>{@code @Component} Annotation</h3>
 * <p>Marks this class as a Spring-managed bean. Spring will create one instance
 * and make it available for injection wherever needed. The service layer
 * receives it via constructor injection.
 */
@Component
public class MonitorMapper {

    /**
     * Converts a {@link CreateMonitorRequest} DTO to a new {@link Monitor} entity.
     *
     * <p>This method handles:
     * <ul>
     *   <li>Setting required fields from the request</li>
     *   <li>Converting the String httpMethod to the enum type</li>
     *   <li>Applying all optional fields with their request-provided or default values</li>
     * </ul>
     *
     * <p>Fields NOT set here (managed by the system):
     * <ul>
     *   <li>{@code id} — auto-generated by PostgreSQL</li>
     *   <li>{@code status} — defaults to UNKNOWN via entity constructor</li>
     *   <li>{@code consecutiveFailures} — defaults to 0 via entity</li>
     *   <li>{@code lastCheckedAt} — null until first check</li>
     *   <li>{@code createdAt} / {@code updatedAt} — set in the Monitor constructor</li>
     * </ul>
     *
     * @param request the validated create request
     * @return a new Monitor entity ready to be persisted
     * @throws IllegalArgumentException if httpMethod is not a valid enum value
     */
    public Monitor toEntity(CreateMonitorRequest request) {
        Monitor monitor = new Monitor(request.getName(), request.getUrl());

        // Convert String → HttpMethod enum.
        // valueOf() throws IllegalArgumentException for invalid values like "POST".
        // The service layer catches this and converts it to a user-friendly error.
        monitor.setHttpMethod(HttpMethod.valueOf(request.getHttpMethod().toUpperCase()));

        monitor.setExpectedStatus(request.getExpectedStatus());
        monitor.setCheckInterval(request.getCheckInterval());
        monitor.setTimeout(request.getTimeout());
        monitor.setFailureThreshold(request.getFailureThreshold());

        return monitor;
    }

    /**
     * Converts a {@link Monitor} entity to a {@link MonitorResponse} DTO.
     *
     * <p>This is the "outbound" direction — entity data going to the API client.
     * Enum values are converted to strings for the response (the client doesn't
     * need to know about our internal Java enum types).
     *
     * @param monitor the entity to convert
     * @return the API response representation
     */
    public MonitorResponse toResponse(Monitor monitor) {
        MonitorResponse response = new MonitorResponse();

        response.setId(monitor.getId());
        response.setName(monitor.getName());
        response.setUrl(monitor.getUrl());
        response.setHttpMethod(monitor.getHttpMethod().name());
        response.setExpectedStatus(monitor.getExpectedStatus());
        response.setCheckInterval(monitor.getCheckInterval());
        response.setTimeout(monitor.getTimeout());
        response.setActive(monitor.getActive());
        response.setStatus(monitor.getStatus().name());
        response.setFailureThreshold(monitor.getFailureThreshold());
        response.setConsecutiveFailures(monitor.getConsecutiveFailures());
        response.setLastCheckedAt(monitor.getLastCheckedAt());
        response.setCreatedAt(monitor.getCreatedAt());
        response.setUpdatedAt(monitor.getUpdatedAt());

        return response;
    }
}
